"""
话题边界守卫（Domain Guard）
============================
判断用户提问是否落在「中国交通出行法规」领域内（涵盖道路交通、
高速公路、铁路高铁、城市轨道交通、民用航空等出行方式）。

为什么需要它：
--------------------------------------------------
实测发现，nomic-embed-text 对中文通用短句的向量区分度不足：
    「今天天气怎么样？」 语义相似度 0.677
    「帮我写一首关于春天的诗」 0.653
    「闯红灯扣几分？」 语义相似度 0.632
无关问题的语义分甚至高于合法提问，因此**不能**用余弦相似度做离题判定
（否则会大量误伤或漏判）。检索阶段混合加权引入的 keyword_boost 虽有一定
区分度，但仍会因「天气/机动」等偶然共现产生噪声。

本模块采用「确定性术语词表 + 会话上下文」的轻量闸门，优点：
1. 规则透明、可解释、可复现，不依赖小模型的指令遵循能力；
2. 判定在检索之后、生成之前完成，离题问题零大模型调用，CPU 推理环境下
   可显著节省算力并做到秒回；
3. 与 Prompt 中的拒答规则形成双层保险：守卫拦截「明显离题」，
   Prompt 负责「属于交通话题但知识库依据不足」的情形。

判定优先级（依次短路）：
    1. 命中交通领域术语            → 领域内（放行）
    2. 命中明确的其他领域主题词    → 离题（优先于多轮放行，防止话题突变）
    3. 检索 Top-1 的术语命中率够高 → 领域内（词表遗漏的兜底）
    4. 有历史且确实像追问          → 视为对上一轮的追问（放行）
    5. 其余                        → 离题
"""

