# 可引导的交通线索：若离题问题里恰好提到这些词，说明用户其实有出行相关意图，
# 可以顺势更精准地把话题拉回到对应的出行方式上。
_GUIDE_HINTS: tuple = (
    "车", "开车", "高铁", "火车", "地铁", "飞机", "出行", "驾照",
    "驾驶证", "上路", "坐车", "乘", "旅行", "出差", "回家", "赶车",
)


def hit_domain_terms(query: str) -> List[str]:
    """返回问题中命中的交通领域术语（有序、去重）。"""
    q = (query or "").strip()
    seen: List[str] = []
    for term in DOMAIN_TERMS:
        if term in q and term not in seen:
            seen.append(term)
    return seen


def hit_off_topic_terms(query: str) -> List[str]:
    """返回问题中命中的其他领域主题词。"""
    q = (query or "").strip()
    return [t for t in OFF_TOPIC_TERMS if t in q]


def _top_keyword_boost(results: Optional[List[Dict[str, Any]]]) -> float:
    """取检索 Top-1 的关键词命中率，作为词表遗漏时的兜底信号。"""
    if not results:
        return 0.0
    value = results[0].get("keyword_boost", 0.0)
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def looks_like_followup(query: str) -> bool:
    """判断短问题是否像「接着上一轮问」的追问（那 / 呢 / 再 / 如果…）。"""
    q = (query or "").strip()
    if not q or len(q) > 24:
        return False
    return any(marker in q for marker in FOLLOWUP_MARKERS)


def is_off_topic(
    query: str,
    results: Optional[List[Dict[str, Any]]] = None,
    has_history: bool = False,
) -> bool:
    """
    判断问题是否离题。

    参数
    ----
    query : 用户原始问题
    results : 向量检索结果（可为 None，表示尚未检索）
    has_history : 当前会话是否已有历史轮次（用于放行「那我该怎么办呢」式追问）
    """
    q = (query or "").strip()
    if not q:
        return False  # 空问题交由上层处理

    # 1. 明确的交通术语 → 领域内
    if hit_domain_terms(q):
        return False

    # 2. 明确的其他领域主题词 → 离题（优先于多轮放行，防止话题突变）
    if hit_off_topic_terms(q):
        return True

    # 3. 检索兜底：术语命中率足够高，说明词表虽未覆盖但确实相关
    if _top_keyword_boost(results) >= Config.GUARD_MIN_KEYWORD_BOOST:
        return False

    # 4. 有历史且确实像追问 → 放行（放行条件收紧，避免「写首诗」被误当作追问）
    if has_history and looks_like_followup(q):
        return False

    # 5. 无术语、无有效追问、检索也弱 → 离题
    return True


def pick_reply(query: str) -> str:
    """按问题内容稳定选取一条引导话术（同一问题始终得到同一回复）。

    选取策略：
    - 若离题问题里提到交通线索词（如「开车」「高铁」），优先选后半段
      更聚焦出行方式的话术，让引导更贴近用户上下文；
    - 否则用字符和取模，在多条话术间稳定轮转，避免每次都是同一句。
    """
    q = (query or "").strip()
    # 含交通线索词：从第 3、4 条里选，语气更聚焦「出行方式」引导
    if any(hint in q for hint in _GUIDE_HINTS):
        base = len(OFF_TOPIC_REPLIES) // 2
        index = base + (sum(ord(ch) for ch in q) % (len(OFF_TOPIC_REPLIES) - base))
    else:
        index = sum(ord(ch) for ch in q) % len(OFF_TOPIC_REPLIES)
    return OFF_TOPIC_REPLIES[index]


